namespace Game.Core.Diagnostics;

/// <summary>
/// Уровень важности записи журнала.
/// Порядок значений совпадает с порядком возрастания важности (GDD §16.2).
/// </summary>
public enum LogLevel
{
    /// <summary>Трассировка: мельчайшие шаги симуляции.</summary>
    Trace = 0,

    /// <summary>Отладка: диагностические подробности для разработки.</summary>
    Debug = 1,

    /// <summary>Информация: штатные события жизненного цикла.</summary>
    Info = 2,

    /// <summary>Предупреждение: подозрительная, но не сломанная ситуация.</summary>
    Warning = 3,

    /// <summary>Ошибка: операция не выполнена, игра может продолжать работу.</summary>
    Error = 4,

    /// <summary>Критическая ошибка: продолжение работы невозможно.</summary>
    Critical = 5
}
