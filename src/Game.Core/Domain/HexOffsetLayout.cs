namespace Game.Core.Domain;

/// <summary>
/// Схема преобразования аксиальных координат в offset-координаты (столбец/строка).
/// Используется только на границе домена: для сериализации карт и моста к рендеру.
/// Вся логика карты и боя работает в аксиальных координатах (ADR-003).
/// </summary>
public enum HexOffsetLayout
{
    /// <summary>Нечётные строки сдвинуты вправо (odd-r). Схема по умолчанию для карт проекта.</summary>
    OddR = 0,

    /// <summary>Чётные строки сдвинуты вправо (even-r).</summary>
    EvenR = 1
}
