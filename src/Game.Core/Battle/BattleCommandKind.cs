namespace Game.Core.Battle;

/// <summary>
/// Вид команды игрока или ИИ в бою. Контратака командой не является (GDD §7.3).
/// </summary>
public enum BattleCommandKind
{
    /// <summary>Переместиться на свободный гекс; тратит очки движения, ход не завершается.</summary>
    Move = 0,

    /// <summary>Ожидание: перенос хода в конец раунда.</summary>
    Wait = 1,

    /// <summary>Защита: +25 % к защите до следующего хода стака.</summary>
    Defend = 2,

    /// <summary>
    /// Атака стака: ближняя (при необходимости с автоматическим подходом) или дальняя; завершает ход.
    /// </summary>
    Attack = 3,

    /// <summary>Активная способность стака (кулдаун); завершает ход стака.</summary>
    UseAbility = 4,

    /// <summary>Заклинание героя из командной панели: 1 за раунд, мана; ход стака не завершает.</summary>
    CastSpell = 5,

    /// <summary>Командная способность героя: 1 за бой; ход стака не завершает (до этапа героев — заглушка).</summary>
    UseCommandAbility = 6
}
